/**
 * Что открыть в редакторе уровня, например по замечанию пользователя: тема (номер с 1) или вопрос теста.
 * `key` меняется при каждом переходе, чтобы повторный переход к тому же месту тоже срабатывал.
 */
export type EditorFocus = {
  step: number | 'quiz'
  /** Номер варианта теста (с 0); без него — первый вариант. */
  quizVariant?: number
  /** Индекс вопроса в варианте теста. */
  questionIndex?: number
  key: number
}
